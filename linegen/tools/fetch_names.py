"""
Builds the closed list of proper names a line may use, from the OSRS Wiki's structured data.

Writes two files into src/test/resources/com/chattynpcs/:
- wiki_names.txt: every page name of an NPC, monster, item, location, shop or piece of scenery.
  The test that checks names reads this alongside names.txt, the hand-reviewed list of lore words
  that have no infobox of their own.
- quest_titles.txt: every quest's title, for the test that nobody names a quest.

Run from the repository root:  python3 linegen/tools/fetch_names.py
The wiki asks for a descriptive User-Agent and one request at a time, so this is slow on purpose.
"""
import json
import sys
import time
import urllib.parse
import urllib.request

API = "https://oldschool.runescape.wiki/api.php"
AGENT = "chatty-npcs name list (RuneLite plugin; github.com/mrgnomnom/chatty-npcs)"
TABLES = ["infobox_npc", "infobox_monster", "infobox_item", "infobox_location", "infobox_shop", "infobox_scenery"]
PAGE = 5000
OUT = "src/test/resources/com/chattynpcs/"
HEADER = "# Generated by linegen/tools/fetch_names.py from the OSRS Wiki (CC BY-NC-SA 3.0). Do not edit by hand.\n"


def query(table, offset):
	q = "bucket('%s').select('page_name').limit(%d).offset(%d).run()" % (table, PAGE, offset)
	url = API + "?" + urllib.parse.urlencode({"action": "bucket", "format": "json", "query": q})
	request = urllib.request.Request(url, headers={"User-Agent": AGENT})
	with urllib.request.urlopen(request, timeout=60) as response:
		body = json.load(response)
	if "error" in body:
		raise RuntimeError(table + ": " + json.dumps(body["error"]))
	return [row["page_name"] for row in body["bucket"]]


def fetch(table):
	names = set()
	offset = 0
	while True:
		rows = query(table, offset)
		names.update(rows)
		print("%s: %d" % (table, offset + len(rows)), file=sys.stderr)
		if len(rows) < PAGE:
			break
		offset += PAGE
		time.sleep(1)
	time.sleep(1)
	# "Cook (Lumbridge)" is the page; "Cook" is the name
	return {name[:name.index(" (")] if " (" in name else name for name in names}


def write(file, names):
	with open(OUT + file, "w", encoding="utf-8", newline="\n") as out:
		out.write(HEADER)
		for name in sorted(n.strip() for n in names):
			out.write(name + "\n")
	print("%s: %d names" % (file, len(names)), file=sys.stderr)


def main():
	names = set()
	for table in TABLES:
		names |= fetch(table)
	write("wiki_names.txt", names)
	write("quest_titles.txt", fetch("quest"))


if __name__ == "__main__":
	main()
